"use client";
import { summarizePolicy, type Policy } from "@agent/policy/policy";
import { useSearchParams } from "next/navigation";
import { Suspense, useState } from "react";
import { ActAs, ImportKey } from "@/components/ActAs";
import { AgentBadge, AiBadge } from "@/components/Attestation";
import { Ladder } from "@/components/Ladder";
import { ActionButton, Card, ErrorNote, Field, inputCls, Pill } from "@/components/ui";
import { NotificationLog, Releases, SignalList, WatchStatus } from "@/components/WillParts";
import { agent, type DraftResult } from "@/lib/agent";
import { DEMO_TIMINGS, REAL_TIMINGS } from "@/lib/config";
import { addSealedNote, createWill } from "@/lib/demo";
import { useKeys, useWill } from "@/lib/hooks";
import { call, formatNear, nearToYocto, signRequest } from "@/lib/near";
import { ago, duration, stateName, type Will } from "@/lib/will";

export default function OwnerPage() {
  return (
    <Suspense>
      <Owner />
    </Suspense>
  );
}

function Owner() {
  const params = useSearchParams();
  const { casts } = useKeys();
  const [owner, setOwner] = useState(params.get("as") ?? "");
  const { data: will, loaded, refresh } = useWill(owner || null, 4000);
  // Keep the writing view until every creation step has finished, even after the will shows up on-chain
  const [creating, setCreating] = useState(false);

  return (
    <div className="space-y-6">
      <div className="space-y-3">
        <h1 className="font-serif text-3xl">Your will</h1>
        <ActAs value={owner} onChange={setOwner} suggested={casts.map((c) => c.owner)} />
        <ImportKey />
      </div>
      {owner && loaded && (!will || creating) && <WriteWill owner={owner} onCreating={setCreating} onCreated={refresh} />}
      {owner && will && !creating && <Dashboard will={will} refresh={refresh} />}
    </div>
  );
}

function WriteWill({ owner, onCreating, onCreated }: { owner: string; onCreating: (b: boolean) => void; onCreated: () => void }) {
  const [text, setText] = useState("");
  const [draft, setDraft] = useState<DraftResult | null>(null);
  const [demoClock, setDemoClock] = useState(true);
  const [contacts, setContacts] = useState("");
  const [deposit, setDeposit] = useState("0.5");
  const [log, setLog] = useState<string[]>([]);
  const policy = draft?.ok ? (draft.policy as Policy) : null;
  const assets = new Set(policy?.allocations.map((a) => a.asset));

  return (
    <div className="grid gap-6 lg:grid-cols-[1.3fr_1fr]">
      <Card title="Write it in plain English">
        <p className="mb-3 text-sm text-muted">
          Say who gets what, how many stages, and who your guardians are. A private model on NEAR AI Cloud drafts the structured version; nothing is
          saved until you approve the summary.
        </p>
        <textarea
          className={`${inputCls} h-40 w-full`}
          value={text}
          onChange={(e) => setText(e.target.value)}
          placeholder={`I leave all my NEAR to my son Bola (bola.testnet). Release it in three stages: 10%, 30%, 60%. My guardians are g1.testnet, g2.testnet and g3.testnet; two must confirm.`}
        />
        <div className="mt-3">
          <ActionButton
            disabled={text.trim().length < 10}
            onClick={async () => {
              setDraft(null);
              setDraft(await agent.draftPolicy(await signRequest(owner, "draft_policy", { text })));
            }}
          >
            Draft my will
          </ActionButton>
        </div>
        {draft && !draft.ok && (
          <div className="mt-4 space-y-2">
            <ErrorNote>The draft doesn&apos;t add up yet. Nothing was fixed automatically; please reword and try again.</ErrorNote>
            <ul className="list-disc pl-5 text-sm">
              {draft.errors.map((e) => (
                <li key={e}>{e}</li>
              ))}
            </ul>
          </div>
        )}
        {policy && (
          <div className="mt-4 space-y-3">
            <h3 className="font-serif text-lg">Please check this summary</h3>
            <ul className="list-disc space-y-1 pl-5 text-sm">
              {summarizePolicy(policy).map((l) => (
                <li key={l}>{l}</li>
              ))}
            </ul>
            <p className="text-xs text-muted">
              This summary is generated by code from the validated policy, not by the model. Response signed by the attested model:{" "}
              {draft?.ai.signature?.ok ? "verified" : "not verified"}.
            </p>
            <div className="grid gap-3 sm:grid-cols-2">
              <Field label="Welfare-check contacts" hint="NEAR accounts, comma-separated (optional)">
                <input className={inputCls} value={contacts} onChange={(e) => setContacts(e.target.value)} placeholder="friend.testnet" />
              </Field>
              <Field label="NEAR to put in the vault now">
                <input className={inputCls} value={deposit} onChange={(e) => setDeposit(e.target.value)} />
              </Field>
            </div>
            <label className="flex items-center gap-2 text-sm">
              <input type="checkbox" checked={demoClock} onChange={(e) => setDemoClock(e.target.checked)} />
              Demo clock (quiet after {duration(DEMO_TIMINGS.quiet_after)} instead of {duration(REAL_TIMINGS.quiet_after)})
            </label>
            <ActionButton
              onClick={async () => {
                setLog([]);
                onCreating(true);
                try {
                  await createWill(
                  owner,
                  {
                    policy,
                    contacts: contacts.split(",").map((c) => c.trim()).filter(Boolean),
                    timings: demoClock ? DEMO_TIMINGS : REAL_TIMINGS,
                    foreignChains: [...(assets.has("ETH") ? ["Eth" as const] : []), ...(assets.has("BTC") ? ["Btc" as const] : [])],
                    depositNear: deposit,
                  },
                  (m) => setLog((l) => [...l, m]),
                );
                  onCreated();
                } finally {
                  onCreating(false);
                }
              }}
            >
              Approve and create my will
            </ActionButton>
            <ul className="font-mono text-xs text-muted">
              {log.map((l, i) => (
                <li key={i}>{l}</li>
              ))}
            </ul>
          </div>
        )}
      </Card>
      <Card title="Private by construction">
        <AiBadge />
        <p className="mt-3 text-sm text-muted">
          Your words are sent only to a model whose TEE attestation the agent has just checked (Intel TDX quote, NVIDIA GPU attestation, signing key
          bound to a fresh nonce). The response must carry a signature from that attested key.
        </p>
      </Card>
    </div>
  );
}

function Dashboard({ will, refresh }: { will: Will; refresh: () => void }) {
  const owner = will.owner;
  const s = stateName(will.state);
  const active = s === "Active";
  return (
    <div className="grid gap-6 lg:grid-cols-[1fr_1.1fr]">
      <div className="space-y-6">
        <Card title="Where your will is">
          <WatchStatus owner={owner} will={will} canSign />
          <Ladder will={will} />
          <div className="mt-4 flex flex-wrap items-center gap-3">
            <ActionButton disabled={s === "Completed"} onClick={() => call(owner, "i_am_alive").then(refresh)}>
              I&apos;m alive
            </ActionButton>
            <span className="text-xs text-muted">Cancels any stage, including execution. You never need to press it in normal life.</span>
          </div>
        </Card>
        <Card title="Signs of life the agent watches">
          <SignalList owner={owner} will={will} />
          <WatchSettings owner={owner} />
        </Card>
        <Card title="People">
          <dl className="space-y-1 text-sm">
            {will.heirs.map((h) => (
              <div key={h.account_id} className="flex flex-wrap justify-between gap-2">
                <dt>
                  Heir: {h.name} <span className="text-muted">({h.account_id})</span>
                </dt>
                <dd className="text-muted">{h.near_share_bps / 100}% of NEAR</dd>
              </div>
            ))}
            <div className="flex flex-wrap justify-between gap-2">
              <dt>Guardians</dt>
              <dd className="text-muted">
                {will.guardian_threshold} of {will.guardians.length}: {will.guardians.join(", ")}
              </dd>
            </div>
            {will.contacts.length > 0 && (
              <div className="flex flex-wrap justify-between gap-2">
                <dt>Welfare contacts</dt>
                <dd className="text-muted">{will.contacts.join(", ")}</dd>
              </div>
            )}
          </dl>
          <p className="mt-2 text-xs text-muted">Stages: {will.stages_pct.map((p) => `${p}%`).join(" → ")}. Policy hash {will.policy_hash.slice(0, 16)}…</p>
        </Card>
      </div>
      <div className="space-y-6">
        <Card title="NEAR vault">
          <p className="text-2xl">{formatNear(will.near_balance)} NEAR</p>
          {active ? <NearVaultActions owner={owner} refresh={refresh} /> : <p className="text-xs text-muted">Deposits and withdrawals are open while the will is Active.</p>}
          {will.foreign_chains.length > 0 && (
            <p className="mt-2 text-xs text-muted">Foreign vaults: {will.foreign_chains.join(", ")} (see the demo panel for addresses and balances).</p>
          )}
        </Card>
        <SealedNotes will={will} refresh={refresh} />
        <Card title="Released so far">
          <Releases will={will} />
        </Card>
        <Card title="Notifications">
          <NotificationLog owner={owner} />
        </Card>
        <Card title="Trust">
          <AgentBadge />
        </Card>
      </div>
    </div>
  );
}

function NearVaultActions({ owner, refresh }: { owner: string; refresh: () => void }) {
  const [amount, setAmount] = useState("0.1");
  return (
    <div className="mt-3 flex flex-wrap items-start gap-2">
      <input className={`${inputCls} w-24`} value={amount} onChange={(e) => setAmount(e.target.value)} />
      <ActionButton tone="quiet" onClick={() => call(owner, "deposit_near", {}, nearToYocto(amount)).then(refresh)}>
        Deposit
      </ActionButton>
      <ActionButton
        tone="quiet"
        onClick={() => call(owner, "request_withdrawal", { chain: "Near", to: owner, amount: nearToYocto(amount).toString() }, 0n, 100n).then(refresh)}
      >
        Withdraw to me
      </ActionButton>
    </div>
  );
}

function WatchSettings({ owner }: { owner: string }) {
  const [evm, setEvm] = useState("");
  const [github, setGithub] = useState("");
  const [saved, setSaved] = useState<string | null>(null);
  return (
    <details className="mt-4 text-sm">
      <summary className="cursor-pointer text-muted hover:text-ink">Add sources (signed by you)</summary>
      <div className="mt-2 grid gap-2 sm:grid-cols-2">
        <Field label="Your personal Sepolia address" hint="Not the vault. Outgoing transactions count as signs of life.">
          <input className={inputCls} value={evm} onChange={(e) => setEvm(e.target.value.trim())} placeholder="0x…" />
        </Field>
        <Field label="GitHub username" hint="Public events only.">
          <input className={inputCls} value={github} onChange={(e) => setGithub(e.target.value.trim())} />
        </Field>
      </div>
      <div className="mt-2">
        <ActionButton
          tone="quiet"
          onClick={async () => {
            const data: Record<string, string> = {};
            if (evm) data.evm_address = evm;
            if (github) data.github = github;
            await agent.registerOwner(await signRequest(owner, "register_owner", data));
            setSaved("Saved. The agent checks every 15 s.");
          }}
        >
          Save
        </ActionButton>
        {saved && <span className="ml-2 text-xs text-accent">{saved}</span>}
      </div>
      <p className="mt-2 text-xs text-muted">This replaces the previous list. Your NEAR account and the heartbeat app are always watched.</p>
    </details>
  );
}

function SealedNotes({ will, refresh }: { will: Will; refresh: () => void }) {
  const [heir, setHeir] = useState(will.heirs[0]?.account_id ?? "");
  const [label, setLabel] = useState("");
  const [text, setText] = useState("");
  const active = stateName(will.state) === "Active";
  return (
    <Card title="Sealed notes" aside={<Pill>{will.sealed_notes.length} of 10</Pill>}>
      <p className="text-sm text-muted">
        Encrypted in this browser to the agent&apos;s TEE key. Only ciphertext goes on-chain. After execution starts, the agent re-seals each note to
        its heir&apos;s own key.
      </p>
      <ul className="mt-3 space-y-1 text-sm">
        {will.sealed_notes.map((n) => {
          const released = will.released_notes.some((r) => r.note_id === n.id);
          return (
            <li key={n.id} className="flex flex-wrap items-center justify-between gap-2">
              <span>
                {n.label} <span className="text-muted">for {n.heir}</span> {released && <Pill tone="accent">released</Pill>}
              </span>
              {active && (
                <ActionButton tone="quiet" onClick={() => call(will.owner, "remove_sealed_note", { note_id: n.id }).then(refresh)}>
                  Remove
                </ActionButton>
              )}
            </li>
          );
        })}
        {will.sealed_notes.length === 0 && <li className="text-muted">No notes yet.</li>}
      </ul>
      {active && (
        <div className="mt-4 space-y-2">
          <div className="grid gap-2 sm:grid-cols-2">
            <select className={inputCls} value={heir} onChange={(e) => setHeir(e.target.value)}>
              {will.heirs.map((h) => (
                <option key={h.account_id} value={h.account_id}>
                  for {h.name}
                </option>
              ))}
            </select>
            <input className={inputCls} placeholder="Label (visible on-chain)" value={label} onChange={(e) => setLabel(e.target.value)} maxLength={64} />
          </div>
          <textarea className={`${inputCls} h-24 w-full`} placeholder="Instructions (encrypted before they leave this page)" value={text} onChange={(e) => setText(e.target.value)} />
          <ActionButton
            disabled={!label || !text}
            onClick={async () => {
              await addSealedNote(will.owner, heir, label, text);
              setText("");
              setLabel("");
              refresh();
            }}
          >
            Seal and save
          </ActionButton>
          <p className="text-xs text-muted">
            Tip: don&apos;t put a whole secret in one note. Split a seed phrase from its passphrase, or describe where things are instead.
          </p>
        </div>
      )}
      {will.released_notes.length > 0 && <p className="mt-2 text-xs text-muted">Last release {ago(will.released_notes[will.released_notes.length - 1].at)}.</p>}
    </Card>
  );
}
